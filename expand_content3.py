def expand_main(html, extras):
    for h2, paras in extras.items():
        insert = "".join(f"<p>{p}</p>" for p in paras)
        pattern = rf'(<h2>{re.escape(h2)}</h2>)(.*?)(</div></div></section>)'
        html, _ = re.subn(
            pattern, lambda m: m.group(1) + m.group(2) + insert + m.group(3),
            html, count=1, flags=re.DOTALL,
        )
    return html


def add_section(html, h2, *paras):
    ps = "".join(f"<p>{p}</p>" for p in paras)
    block = f'<section class="section-block"><div class="container"><div class="text-wrap"><h2>{h2}</h2>{ps}</div></div></section>'
    return html.replace('<section class="section-block section-cta">', block + '\n    <section class="section-block section-cta">', 1)


def expand_faq(html, mapping):
    for q, new_a in mapping.items():
        pattern = rf'(<h3>{re.escape(q)}</h3><p>)(.*?)(</p>)'
        html, n = re.subn(pattern, rf'\1{new_a}\3', html, count=1, flags=re.DOTALL)
        if n == 0:
            print("WARN FAQ not found:", q)
    return html


def count_words(main):
    body = re.sub(r"<[^>]+>", " ", main)
    return len(re.findall(r"[\w\u0400-\u04FF]+", body))


def check_dups(main):
    paras = re.findall(r"<p[^>]*>(.*?)</p>", main, re.S)
    texts = [re.sub(r"<[^>]+>", "", p).strip() for p in paras if p.strip()]
    return sum(1 for c in collections.Counter(texts).values() if c > 1)


def check_forbidden(main):
    found = [f for f in FORBIDDEN if f.lower() in main.lower()]
    return found


